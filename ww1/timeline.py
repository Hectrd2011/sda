# ----------------------------------------------------------------------------- helpers
def day_index(d):
    return (d - START).days


def resolve_line(items):
    pts = []
    for it in items:
        if isinstance(it, tuple) and len(it) == 5 and it[0] == "B":
            seg = geo.border_between(it[1], it[2], np.array(it[3]), np.array(it[4]))
            pts.extend(seg)
        else:
            pts.append(tuple(map(float, it)))
    out = [pts[0]]
    for p in pts[1:]:
        if abs(p[0] - out[-1][0]) > 1e-6 or abs(p[1] - out[-1][1]) > 1e-6:
            out.append(p)
    return np.array(out)


def resample(line, n):
    seg = np.sqrt(((line[1:] - line[:-1]) ** 2).sum(1))
    s = np.concatenate([[0], np.cumsum(seg)])
    t = np.linspace(0, s[-1], n)
    return np.stack([np.interp(t, s, line[:, 0]), np.interp(t, s, line[:, 1])], 1)


def interp_series(series, t, ease=True):
    """series: [(day_float, value)], t: day float -> value (clamped)."""
    if t <= series[0][0]:
        return series[0][1]
    for (t0, v0), (t1, v1) in zip(series, series[1:]):
        if t <= t1:
            u = (t - t0) / max(t1 - t0, 1e-9)
            if ease:
                u = u * u * (3 - 2 * u)
            return v0 + (v1 - v0) * u
    return series[-1][1]


def as_day(s):
    return day_index(D(s))


def date_at(day_float):
    return START + timedelta(days=int(np.floor(day_float)))
